import re
_hangul = re.compile(r'[가-힣㄰-㆏]'); _alpha = re.compile(r'[A-Za-z]')
def lookup(en, table, add_period):
    """영어 문장 en의 번역. 없으면 KeyError (영어로 슬쩍 넘기지 않음)."""
    if en in table: return table[en]
    if en.endswith('.') and en[:-1] in table: return table[en[:-1]] + ('.' if add_period else '')
    if not en.endswith('.') and (en + '.') in table: return table[en + '.'].rstrip('.')
    if ' · ' in en:
        return ' · '.join(p if (_hangul.search(p) or not _alpha.search(p)) else lookup(p, table, add_period) for p in en.split(' · '))
    raise KeyError(en)
